const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const sport=fs.existsSync(path.join(root,'research.js'))?'NHL':fs.existsSync(path.join(root,'app.js'))?'NFL':'NBA';
const filename=sport==='NHL'?'research.js':sport==='NFL'?'app.js':'index.html';
const source=fs.readFileSync(path.join(root,filename),'utf8');
const start=source.indexOf('function renderComparisonReport(');
const end=source.indexOf('\nfunction ',start+10);
const context={};
vm.createContext(context);
vm.runInContext(source.slice(start,end),context);
const render=context.renderComparisonReport;
const surface=sport==='NFL'?'PUBLIC_BOARD':'RESEARCH_FEED';
const row={POLICY:'first-pregame-selection-v1',SPORT:sport,SURFACE:surface,EVIDENCE:'ALL',TIME_WINDOW:'last_30d',N_SELECTED:4,N_HITS:1,N_MISSES:1,N_PUSHES:1,N_DNP:0,N_PENDING:1,N_PRICED:3,HIT_RATE:0.5,ROI_PCT:-3,NET_UNITS:-0.09};
assert.match(render([row],'last_30d',sport,surface),/50.0%/);
assert.match(render([row],'last_30d',sport,surface),/-3.0%/);
assert.match(render([row],'last_7d',sport,surface),/No comparison results/);
assert.match(render([],'last_30d',sport,surface),/unavailable/);
assert.match(render([{...row,POLICY:'old'}],'last_30d',sport,surface),/unavailable/);
assert.match(render([row,row],'last_30d',sport,surface),/inconsistent/);
assert.match(render([{...row,N_SELECTED:500}],'last_30d',sport,surface),/inconsistent/);
assert.match(render([{...row,N_PRICED:0,ROI_PCT:'',NET_UNITS:''}],'last_30d',sport,surface),/Not available/);
const evidence={...row,EVIDENCE:'RECONSTRUCTED'};
assert.match(render([row,evidence],'last_30d',sport,surface),/Reconstructed pregame feed/);
assert.doesNotMatch(render([row],'last_30d',sport,surface),/Flat -115|tier collapse/);
const loader=fs.readFileSync(path.join(root,sport==='NBA'?'index.html':'app.js'),'utf8');
assert.match(loader,/st.comparisonPerformance=normalizeKeys\(cleanRows\(await fetch(?:Optional)?Sheet\("Comparison_Performance"\)/);
console.log(sport+': comparison display, window, invalid data and loading wiring checks passed');

